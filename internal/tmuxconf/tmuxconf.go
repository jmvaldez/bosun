// Package tmuxconf generates the tmux conf bosun owns. bosun loads it into the
// running tmux itself (`bosun setup`, and the plugin's SessionStart hook); the
// user's own tmux config is never edited (D-31).
package tmuxconf

import (
	"fmt"
	"strings"
)

// AttachHook is the fixed client-attached array index Generate sets. A fixed
// index makes sourcing idempotent, and lets uninstall find exactly its entry.
const AttachHook = "client-attached[42]"

// LoadedOption is the tmux server option the conf ends by setting to its own
// version. A server that reports the current version has loaded the current
// conf, so the SessionStart hook leaves it alone.
const LoadedOption = "@bosun-version"

type Options struct {
	Version  string
	Bosun    string // absolute path of the bosun binary
	JumpKey  string
	PopupKey string
	// SpendKey opens the spend view (prefix + $ by default); empty binds nothing.
	SpendKey string
	// ASCII uses ! ^ + <> on the tabs instead of ⚑ ▲ ✓ ⇄ (ui.glyphs = "ascii").
	ASCII bool
}

// Header is the first line of the generated file; doctor compares versions
// through it.
func Header(version string) string { return "# bosun " + version }

// WinMark is the tab marker format: a colored glyph after the window name for
// the four states that want you, nothing for working or idle. Each style block
// carries one attribute so no comma sits inside a conditional branch (L-05).
func WinMark(ascii bool) string {
	flag, tri, check, swap := "⚑", "▲", "✓", "⇄"
	if ascii {
		flag, tri, check, swap = "!", "^", "+", "<>"
	}
	return "#{?#{==:#{@bosun-wait},needs-you}, #[fg=colour214]" + flag + "#[default]," +
		"#{?#{==:#{@bosun-wait},runaway}, #[fg=colour203]" + tri + "#[default]," +
		"#{?#{==:#{@bosun-wait},handoff}, #[fg=colour51]" + swap + "#[default]," +
		"#{?#{==:#{@bosun-wait},done}, #[fg=colour114]" + check + "#[default],}}}}"
}

// Generate returns the conf text, following the generated-conf rules in
// kit/SPEC.md section 7 (LESSONS L-04 to L-08).
func Generate(o Options) (string, error) {
	// $ is tmux's variable sigil. Only the spend key may hold it, because its bind
	// single-quotes the key.
	for name, v := range map[string]string{"version": o.Version, "bosun path": o.Bosun, "jump key": o.JumpKey, "popup key": o.PopupKey, "spend key": o.SpendKey} {
		if strings.ContainsAny(v, "'\"\n\\#") || (strings.Contains(v, "$") && name != "spend key") {
			return "", fmt.Errorf("tmuxconf: %s %q has characters that cannot be quoted safely in a tmux conf", name, v)
		}
	}
	if o.Bosun == "" || o.JumpKey == "" {
		return "", fmt.Errorf("tmuxconf: bosun path and jump key are required")
	}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("%s", Header(o.Version))
	w("# Generated by `bosun setup`; it is regenerated on upgrade, so do not edit it.")
	w("# bosun sources it into the running tmux after your plugin manager and theme")
	w("# have built status-right and the window formats, which the prepends below need.")
	w("")
	w("# Tab marker. Plain `set -g` keeps the format unexpanded until render time.")
	w("set -g @bosun-win-mark '%s'", WinMark(o.ASCII))
	w("")
	w("# Segment, prepended to the status-right the theme built. -F splices in the")
	w("# current value, so bosun's own #( is escaped. Guarded: a second source is a no-op.")
	w("if -F '#{m:*bosun status*,#{status-right}}' '' \"set -gF status-right '##(%s status --tmux)#{status-right}'\"", o.Bosun)
	w("")
	w("# The labeled bar is about 75 columns; tmux cuts status-right at its length.")
	w("if -F '#{<:#{status-right-length},120}' 'set -g status-right-length 120'")
	w("")
	w("# Tab markers after each window's name, same guard.")
	w("if -F '#{m:*@bosun-win-mark*,#{window-status-format}}' '' \"set -gwF window-status-format '#{window-status-format}##{E:@bosun-win-mark}'\"")
	w("if -F '#{m:*@bosun-win-mark*,#{window-status-current-format}}' '' \"set -gwF window-status-current-format '#{window-status-current-format}##{E:@bosun-win-mark}'\"")
	w("")
	w("# prefix + %s opens the popup. display-popup -T (the title) needs tmux 3.3, so", o.PopupKey)
	w("# the binding is gated on the version at load time (D-3); 3.2 gets no title.")
	w("if -F '#{>=:#{version},3.3}' \"bind %s display-popup -E -w 90%% -h 60%% -T ' bosun ' '%s ui'\" \"bind %s display-popup -E -w 90%% -h 60%% '%s ui'\"", o.PopupKey, o.Bosun, o.PopupKey, o.Bosun)
	w("")
	if o.SpendKey != "" {
		w("")
		w("# prefix + %s opens the spend view. The key is quoted: $ is tmux's variable sigil.", o.SpendKey)
		w("if -F '#{>=:#{version},3.3}' \"bind '%s' display-popup -E -w 90%% -h 80%% -T ' bosun spend ' '%s ui --spend'\" \"bind '%s' display-popup -E -w 90%% -h 80%% '%s ui --spend'\"", o.SpendKey, o.Bosun, o.SpendKey, o.Bosun)
	}
	w("")
	w("# prefix + %s walks the waiting queue.", o.JumpKey)
	w("bind %s run-shell -b '%s jump --queue --client \"#{client_name}\"'", o.JumpKey, o.Bosun)
	w("")
	w("# Catch-up evaluation on attach. A fixed array index makes this idempotent;")
	w("# -ag would add another entry on every source (tmux 3.2a verified).")
	w("set-hook -g '%s' 'run-shell -b \"%s status --catch-up\"'", AttachHook, o.Bosun)
	w("")
	w("# Last, so a server that reports this version has loaded all of the above.")
	w("set -g %s '%s'", LoadedOption, o.Version)
	return b.String(), nil
}
