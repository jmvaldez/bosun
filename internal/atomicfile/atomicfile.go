// Package atomicfile writes state files as temp file plus rename so a reader
// never sees a partial file (LESSONS L-41).
package atomicfile

import (
	"os"
	"path/filepath"
)

// Write replaces path with data, creating parent dirs as needed. The temp file
// lives beside the target so the rename never crosses a filesystem.
func Write(path string, data []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	_, err = f.Write(data)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Chmod(tmp, perm)
	}
	if err == nil {
		err = os.Rename(tmp, path)
	}
	if err != nil {
		os.Remove(tmp)
	}
	return err
}
